export type SssRow = {
  label: string;
  min: number;
  max: number;
  msc: { regular: number; mpf: number; total: number };
  er: { regular: number; mpf: number; ec: number; total: number };
  ee: { regular: number; mpf: number; total: number };
  grand: number;
};

const toNum = (t: string) =>
  t === "--" ? 0 : parseFloat(t.replace(/,/g, "")) || 0;

function parseSssTable(raw: string): SssRow[] {
  const rows: SssRow[] = [];

  for (const line of raw.split("\n")) {
    const m = line
      .trim()
      .match(/^(BELOW\s+[\d,.]+|[\d,.]+\s*-\s*(?:[\d,.]+|Other))\s+(\S.*)$/i);

    if (!m) continue;

    const v = m[2].trim().split(/\s+/).map(toNum);

    if (v.length !== 11) continue;

    const label = m[1].replace(/\s+/g, " ").trim();
    let min = 0;
    let max = Infinity;

    if (/^BELOW/i.test(label)) {
      max = toNum(label.replace(/^BELOW\s+/i, "")) - 0.01;
    } else {
      const [a, b] = label.split("-").map((s) => s.trim());

      min = toNum(a);
      max = /other/i.test(b) ? Infinity : toNum(b);
    }

    rows.push({
      label,
      min,
      max,
      msc: { regular: v[0], mpf: v[1], total: v[2] },
      er: { regular: v[3], mpf: v[4], ec: v[5], total: v[6] },
      ee: { regular: v[7], mpf: v[8], total: v[9] },
      grand: v[10],
    });
  }

  return rows;
}

export const SSS_ROWS: SssRow[] = parseSssTable(RAW);

// Index of the bracket for a monthly salary (-1 if there is no salary).
// Follows the company table exactly, with no minimum.
// Example: 19,500 falls in 19,250 - 19,749.99 -> employee share 975.00
export function sssRowIndex(monthlySalary: number): number {
  if (!(monthlySalary > 0)) return -1;

  let found = 0;

  SSS_ROWS.forEach((row, i) => {
    if (monthlySalary >= row.min) found = i;
  });

  return found;
}
